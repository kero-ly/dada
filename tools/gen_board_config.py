#!/usr/bin/env python3
"""Generate a C header from a board manifest.

The device never parses JSON. Everything the firmware needs is emitted as
preprocessor constants at build time (see docs/adr/0002-board-manifest.md).

Usage:
    python tools/gen_board_config.py hardware/<vendor>/<board>/board.json -o out/dada_board_config.h
    python tools/gen_board_config.py --all -o out/          # one <id>.h per board

Unknown values in the manifest (null) become -1 for numbers and "" for strings,
so a missing pin cannot silently become GPIO0.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent

CAPABILITIES = (
    "display",
    "input",
    "touch",
    "audio",
    "storage",
    "time",
    "usb-serial-jtag",
    "wifi",
    "ble",
)


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num_or_neg1(value: Any) -> str:
    return "-1" if value is None else str(int(value))


def emit(manifest: dict[str, Any], source: Path) -> str:
    sha = hashlib.sha256(source.read_bytes()).hexdigest()
    rel = source.relative_to(REPO_ROOT) if REPO_ROOT in source.parents else source

    lines: list[str] = [
        "/*",
        " * Generated by tools/gen_board_config.py -- do not edit.",
        f" * Source:   {rel.as_posix()}",
        f" * SHA-256:  {sha}",
        " *",
        " * Regenerate with:",
        f" *   python tools/gen_board_config.py {rel.as_posix()} -o <path>/dada_board_config.h",
        " */",
        "",
        "#ifndef DADA_BOARD_CONFIG_H",
        "#define DADA_BOARD_CONFIG_H",
        "",
        f"#define DADA_BOARD_ID          {c_string(manifest['id'])}",
        f"#define DADA_BOARD_STATUS      {c_string(manifest['status'])}",
        f"#define DADA_BOARD_SOC         {c_string(manifest['soc'])}",
        f"#define DADA_BOARD_FLASH_MB    {num_or_neg1(manifest.get('flash_mb'))}",
        f"#define DADA_BOARD_PSRAM_MB    {num_or_neg1(manifest.get('psram_mb'))}",
        f"#define DADA_BOARD_MANIFEST_SHA256 {c_string(sha)}",
        "",
    ]

    usb = manifest.get("usb") or {}
    lines += [
        f"#define DADA_BOARD_USB_MODE    {c_string(usb.get('mode') or '')}",
        f"#define DADA_BOARD_USB_VID_PID {c_string(usb.get('vid_pid') or '')}",
        "",
    ]

    verified = set(manifest.get("verified_capabilities") or [])
    lines.append("/* Verified capabilities: usable in compile-time assertions */")
    for cap in CAPABILITIES:
        macro = "DADA_BOARD_VERIFIED_" + cap.upper().replace("-", "_")
        lines.append(f"#define {macro:<32} {1 if cap in verified else 0}")
    lines.append("")

    display = manifest.get("display")
    if display:
        lines += [
            f"#define DADA_BOARD_HAS_DISPLAY 1",
            f"#define DADA_BOARD_DISPLAY_CONTROLLER {c_string(display['controller'])}",
            f"#define DADA_BOARD_DISPLAY_W    {display['width']}",
            f"#define DADA_BOARD_DISPLAY_H    {display['height']}",
            f"#define DADA_BOARD_DISPLAY_BUS  {c_string(display['bus'])}",
        ]
        pins = display.get("pins") or {}
        if pins:
            for name in sorted(pins):
                macro = "DADA_BOARD_LCD_" + name.upper().replace("-", "_")
                lines.append(f"#define {macro:<32} ({num_or_neg1(pins[name])})")
        else:
            lines.append("#define DADA_BOARD_HAS_DISPLAY_PINS 0")
    else:
        lines += [
            "#define DADA_BOARD_HAS_DISPLAY 0",
            "#define DADA_BOARD_DISPLAY_W    (-1)",
            "#define DADA_BOARD_DISPLAY_H    (-1)",
        ]
    lines.append("")

    touch = manifest.get("touch")
    if touch:
        lines += [
            "#define DADA_BOARD_HAS_TOUCH 1",
            f"#define DADA_BOARD_TOUCH_CONTROLLER {c_string(touch['controller'])}",
            f"#define DADA_BOARD_TOUCH_BUS    {c_string(touch['bus'])}",
            f"#define DADA_BOARD_TOUCH_ADDR   {c_string(touch.get('address') or '')}",
        ]
        pins = touch.get("pins") or {}
        for name in sorted(pins):
            macro = "DADA_BOARD_TP_" + name.upper().replace("-", "_")
            lines.append(f"#define {macro:<32} ({num_or_neg1(pins[name])})")
    else:
        lines.append("#define DADA_BOARD_HAS_TOUCH 0")
    lines.append("")

    notes: list[str] = []
    if display and display.get("notes"):
        notes.append(display["notes"])
    if touch and touch.get("notes"):
        notes.append(touch["notes"])
    if notes:
        lines.append("/* Notes carried over from the manifest */")
        for note in notes:
            lines.append(f"/* - {note} */")
        lines.append("")

    lines += ["#endif /* DADA_BOARD_CONFIG_H */", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", nargs="?", type=Path, help="path to board.json")
    parser.add_argument("--all", action="store_true", help="process every hardware/**/board.json")
    parser.add_argument("-o", "--output", required=True, type=Path,
                        help="output .h file, or a directory when --all is used")
    args = parser.parse_args()

    if args.all:
        sources = sorted((REPO_ROOT / "hardware").rglob("board.json"))
        if not sources:
            print("error: no manifests found", file=sys.stderr)
            return 1
        args.output.mkdir(parents=True, exist_ok=True)
        for src in sources:
            manifest = json.loads(src.read_text(encoding="utf-8-sig"))
            out = args.output / f"{manifest['id']}.h"
            out.write_text(emit(manifest, src), encoding="utf-8")
            print(f"wrote {out}")
        return 0

    if not args.manifest:
        parser.error("provide a manifest path or --all")
    manifest = json.loads(args.manifest.read_text(encoding="utf-8-sig"))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(emit(manifest, args.manifest), encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
