#!/usr/bin/env python3
"""Convert an image into a packed pixel-art frame for the whale app.

The output is the format the apps store under `whale.f0`: 4 bits per cell,
row-major, two cells per byte, indices into the shared 15-colour palette that
`apps/paint` and `apps/whale` use.

Examples
--------
    python tools/image_to_frame.py art.png out/frame.bin
    python tools/image_to_frame.py art.png out/frame.h --cols 80 --rows 60

Requires Pillow (`pip install pillow`). Only your own image is read; nothing is
uploaded or modified in place.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Must match PALETTE in apps/paint/paint_app.c and apps/whale/whale_app.c.
PALETTE = [
    (0xFF, 0xFF, 0xFF), (0xF1, 0xE8, 0xE6), (0xC9, 0xCB, 0xD6), (0x9C, 0xA5, 0xBF),
    (0x7F, 0x88, 0xA7), (0x70, 0x8B, 0xC3), (0x5C, 0x74, 0xB0), (0x58, 0x6C, 0xA1),
    (0x4D, 0x61, 0x96), (0x44, 0x57, 0x8C), (0x38, 0x4C, 0x85), (0x40, 0x4A, 0x73),
    (0x2B, 0x38, 0x67), (0x14, 0x1A, 0x33), (0xF0, 0xB8, 0xC8),
]


def nearest(rgb: tuple[int, int, int]) -> int:
    r, g, b = rgb
    best, best_d = 0, 1 << 30
    for i, (pr, pg, pb) in enumerate(PALETTE):
        d = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2
        if d < best_d:
            best, best_d = i, d
    return best


def convert(image_path: Path, cols: int, rows: int) -> bytes:
    try:
        from PIL import Image
    except ImportError:  # pragma: no cover - depends on the environment
        raise SystemExit("Pillow is required: pip install pillow")

    im = Image.open(image_path).convert("RGB")
    small = im.resize((cols, rows), Image.LANCZOS)
    cells = [nearest(px) for px in small.getdata()]

    packed = bytearray()
    for i in range(0, len(cells), 2):
        hi = cells[i] & 0x0F
        lo = (cells[i + 1] & 0x0F) if i + 1 < len(cells) else 0
        packed.append((hi << 4) | lo)
    return bytes(packed)


def write_header(data: bytes, path: Path, cols: int, rows: int) -> None:
    lines = [
        "/* Generated by tools/image_to_frame.py - do not edit by hand. */",
        "#pragma once",
        "#include <stdint.h>",
        f"/* {cols}x{rows} cells, 4 bits per cell, {len(data)} bytes. */",
        f"static const uint8_t WHALE_FRAME[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path, help="source image (png/jpg/...)")
    parser.add_argument("output", type=Path, help=".bin frame or .h header")
    parser.add_argument("--cols", type=int, default=160)
    parser.add_argument("--rows", type=int, default=120)
    args = parser.parse_args()

    if args.cols <= 0 or args.rows <= 0:
        parser.error("--cols and --rows must be positive")
    if not args.image.is_file():
        parser.error(f"no such image: {args.image}")

    data = convert(args.image, args.cols, args.rows)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.output.suffix.lower() in (".h", ".hpp"):
        write_header(data, args.output, args.cols, args.rows)
    else:
        args.output.write_bytes(data)
    print(f"{args.cols}x{args.rows} -> {len(data)} bytes -> {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
